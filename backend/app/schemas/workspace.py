import uuid
from datetime import datetime
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field, model_validator
from app.core.constants import WorkspaceStatus, WorkspaceVisibility


class CreateWorkspaceRequest(BaseModel):
    """
    Pydantic schema for creating a new Workspace inside an Organization.
    """

    name: str = Field(..., min_length=2, max_length=60, description="Workspace Name")
    slug: Optional[str] = Field(None, max_length=120, description="Custom URL slug (autogenerated if empty)")
    description: Optional[str] = Field(None, max_length=500)
    icon: Optional[str] = Field("💼", max_length=100)
    color: Optional[str] = Field(None, max_length=30)
    theme_color: Optional[str] = Field(None, max_length=30)
    visibility: WorkspaceVisibility = Field(
        default=WorkspaceVisibility.PRIVATE, description="Workspace visibility tier"
    )
    project_type: Optional[str] = Field("internal", max_length=20)
    client_name: Optional[str] = Field(None, max_length=120)
    project_name: Optional[str] = Field(None, max_length=120)
    start_date: Optional[str] = Field(None, max_length=20)
    end_date: Optional[str] = Field(None, max_length=20)
    client_demo_date: Optional[str] = Field(None, max_length=20)
    internal_review_date: Optional[str] = Field(None, max_length=20)
    final_delivery_date: Optional[str] = Field(None, max_length=20)
    reminder_before_demo: Optional[str] = Field("1 day before", max_length=50)
    reminder_before_deadline: Optional[str] = Field("3 days before", max_length=50)
    meeting_duration: Optional[int] = Field(60)
    priority: Optional[str] = Field("medium", max_length=20)

    @model_validator(mode="after")
    def resolve_color(self) -> "CreateWorkspaceRequest":
        if not self.color and self.theme_color:
            self.color = self.theme_color
        if not self.color:
            self.color = "#3B82F6"
        return self


class SwitchWorkspaceRequest(BaseModel):
    workspace_id: uuid.UUID = Field(..., description="Target Workspace ID to activate")


class UpdateWorkspaceRequest(BaseModel):
    """
    Pydantic schema for updating Workspace details.
    """

    name: Optional[str] = Field(None, min_length=2, max_length=100)
    description: Optional[str] = Field(None, max_length=500)
    icon: Optional[str] = Field(None, max_length=100)
    color: Optional[str] = Field(None, max_length=30)
    visibility: Optional[WorkspaceVisibility] = None
    default_model: Optional[str] = Field(None, max_length=100)
    storage_limit: Optional[int] = Field(None, description="Storage limit in MB")
    status: Optional[WorkspaceStatus] = None
    project_type: Optional[str] = None
    client_name: Optional[str] = None
    project_name: Optional[str] = None
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    client_demo_date: Optional[str] = None
    internal_review_date: Optional[str] = None
    final_delivery_date: Optional[str] = None
    reminder_before_demo: Optional[str] = None
    reminder_before_deadline: Optional[str] = None
    meeting_duration: Optional[int] = None
    priority: Optional[str] = None


class WorkspaceResponse(BaseModel):
    """
    Pydantic response schema for Workspace details.
    """

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    organization_id: uuid.UUID
    name: str
    slug: str
    description: Optional[str] = None
    icon: Optional[str] = "💼"
    color: Optional[str] = "#3B82F6"
    visibility: WorkspaceVisibility = WorkspaceVisibility.INTERNAL
    status: WorkspaceStatus = WorkspaceStatus.ACTIVE
    created_by: uuid.UUID
    storage_used: int = 0
    storage_limit: int = 10240
    dataset_count: int = 0
    document_count: int = 0
    chat_count: int = 0
    member_count: int = 1
    default_model: Optional[str] = "openai/gpt-oss-120b"
    role: Optional[str] = "OWNER"
    project_type: Optional[str] = "internal"
    client_name: Optional[str] = None
    project_name: Optional[str] = None
    start_date: Optional[str] = None
    end_date: Optional[str] = None
    client_demo_date: Optional[str] = None
    internal_review_date: Optional[str] = None
    final_delivery_date: Optional[str] = None
    reminder_before_demo: Optional[str] = "1 day before"
    reminder_before_deadline: Optional[str] = "3 days before"
    meeting_duration: Optional[int] = 60
    priority: Optional[str] = "medium"
    last_activity: datetime
    created_at: datetime
    updated_at: datetime
