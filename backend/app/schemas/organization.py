import uuid
from datetime import datetime
from typing import Optional
from pydantic import BaseModel, ConfigDict, Field
from app.core.constants import OrganizationPlan


class CreateOrganizationRequest(BaseModel):
    """
    Pydantic schema for creating a new Organization.
    """

    name: str = Field(..., min_length=2, max_length=100, description="Organization Name")
    slug: Optional[str] = Field(None, max_length=120, description="Custom URL slug (autogenerated if empty)")
    description: Optional[str] = Field(None, max_length=500)
    logo_url: Optional[str] = Field(None, max_length=500)
    website: Optional[str] = Field(None, max_length=255)
    industry: Optional[str] = Field(None, max_length=100)
    country: Optional[str] = Field(None, max_length=100)
    timezone: str = Field(default="UTC", max_length=50)


class UpdateOrganizationRequest(BaseModel):
    """
    Pydantic schema for updating Organization details.
    """

    name: Optional[str] = Field(None, min_length=2, max_length=100)
    description: Optional[str] = Field(None, max_length=500)
    logo_url: Optional[str] = Field(None, max_length=500)
    website: Optional[str] = Field(None, max_length=255)
    industry: Optional[str] = Field(None, max_length=100)
    country: Optional[str] = Field(None, max_length=100)
    timezone: Optional[str] = Field(None, max_length=50)


class OrganizationResponse(BaseModel):
    """
    Pydantic response schema for Organization details.
    """

    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    name: str
    slug: str
    description: Optional[str] = None
    logo_url: Optional[str] = None
    website: Optional[str] = None
    industry: Optional[str] = None
    country: Optional[str] = None
    timezone: str = "UTC"
    plan: OrganizationPlan = OrganizationPlan.FREE
    storage_used: int = 0
    storage_limit: int = 1024
    member_limit: int = 5
    workspace_limit: int = 3
    is_active: bool = True
    is_verified: bool = False
    created_by: uuid.UUID
    created_at: datetime
    updated_at: datetime
