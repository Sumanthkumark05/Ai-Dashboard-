import uuid
from typing import Optional
from fastapi import APIRouter, Depends, Query
from sqlalchemy.ext.asyncio import AsyncSession

from app.database.dependency import get_db
from app.models.user import User
from app.models.workspace import Workspace
from app.schemas.activity import ActivityListResponse, ActivityResponse
from app.security.dependencies import get_current_user
from app.security.workspace_dependency import get_current_workspace
from app.services.activity_service import ActivityService

router = APIRouter(prefix="/activity", tags=["Activity Feed"])


@router.get(
    "",
    response_model=ActivityListResponse,
    summary="List Workspace Activities",
    description="Returns paginated activity timeline entries for the current workspace.",
)
async def list_activities(
    activity_type: Optional[str] = Query(default=None, description="Filter by Activity Type"),
    page: int = Query(default=1, ge=1),
    page_size: int = Query(default=20, ge=1, le=100),
    current_ws: Workspace = Depends(get_current_workspace),
    db: AsyncSession = Depends(get_db),
) -> ActivityListResponse:
    data = await ActivityService.get_activities(
        db=db,
        workspace_id=current_ws.id,
        activity_type=activity_type,
        page=page,
        page_size=page_size,
    )
    items = [ActivityResponse.model_validate(a) for a in data["items"]]
    return ActivityListResponse(
        items=items,
        total_items=data["total_items"],
        page=data["page"],
        page_size=data["page_size"],
    )


