"use client";

import * as React from "react";
import { motion } from "framer-motion";
import { Sparkles, CheckCircle2, RefreshCw } from "lucide-react";
import { aiInsights } from "../mock/dashboard-mock-data";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { toast } from "@/components/feedback/toast";

export function AIInsightsCard() {
  const [isRefreshing, setIsRefreshing] = React.useState(false);

  const handleRefresh = () => {
    setIsRefreshing(true);
    setTimeout(() => {
      setIsRefreshing(false);
      toast.success("AI Insights updated", {
        description: "Re-analyzed developer telemetry and query logs.",
      });
    }, 800);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 12 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.35, delay: 0.1 }}
    >
      <Card className="relative overflow-hidden p-6 border-primary/30 bg-gradient-to-br from-card via-card to-primary/5 shadow-sm">
        {/* Top Header */}
        <div className="flex items-center justify-between gap-4 mb-4">
          <div className="flex items-center gap-2">
            <div className="flex h-8 w-8 items-center justify-center rounded-lg bg-primary/10 text-primary border border-primary/20">
              <Sparkles className="h-4 w-4" />
            </div>
            <div>
              <h3 className="text-base font-bold tracking-tight text-foreground">{aiInsights.title}</h3>
              <p className="text-xs text-muted-foreground">Generated by NeuroDesk Core Engine</p>
            </div>
          </div>
          <div className="flex items-center gap-2">
            <Badge variant="success" size="sm" className="font-semibold">
              {aiInsights.metric}
            </Badge>
            <Button
              variant="ghost"
              size="xs"
              onClick={handleRefresh}
              isLoading={isRefreshing}
              className="h-7 w-7 p-0 text-muted-foreground hover:text-foreground"
              aria-label="Refresh AI insights"
            >
              <RefreshCw className="h-3.5 w-3.5" />
            </Button>
          </div>
        </div>

        {/* Highlight Summary Box */}
        <div className="rounded-lg border border-border bg-muted/40 p-4 mb-4">
          <p className="text-sm font-semibold text-foreground leading-relaxed">
            &ldquo;{aiInsights.summary}&rdquo;
          </p>
        </div>

        {/* Insights Bullets */}
        <div className="space-y-2">
          {aiInsights.highlights.map((highlight: string, index: number) => (
            <div key={index} className="flex items-start gap-2 text-xs text-muted-foreground">
              <CheckCircle2 className="h-3.5 w-3.5 text-success shrink-0 mt-0.5" />
              <span className="leading-normal">{highlight}</span>
            </div>
          ))}
        </div>
      </Card>
    </motion.div>
  );
}
