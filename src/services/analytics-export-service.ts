/**
 * analytics-export-service.ts
 * Frontend service for generating and downloading PDF, CSV, and Excel reports
 * populated with real-time live telemetry data and active filters.
 */

import { SystemTelemetryData } from "./analytics-api";
import { formatBytes } from "@/lib/utils";

export interface ExportFilters {
  dateRange: string;
  selectedWorkspace: string;
  selectedCategory: string;
  selectedOwner: string;
}

export const analyticsExportService = {
  /**
   * Export Analytics Report in PDF, CSV, or Excel (.xlsx) format.
   */
  async exportReport(
    format: "pdf" | "csv" | "excel",
    telemetry: SystemTelemetryData,
    filters: ExportFilters,
    workspaceName = "Workspace",
    userName = "Workspace Member"
  ): Promise<void> {
    const sanitizeName = (str: string) => str.replace(/[^a-zA-Z0-9_-]/g, "_");
    const dateStr = new Date().toISOString().split("T")[0];
    const timeStr = new Date().toLocaleTimeString("en-US", { hour12: false });
    const formattedWsName = sanitizeName(workspaceName || "NeuroDesk");
    const extension = format === "excel" ? "xlsx" : format;
    const filename = `Analytics_Report_${formattedWsName}_${dateStr}.${extension}`;

    const timestamp = `${dateStr} ${timeStr} UTC`;

    try {
      if (format === "csv") {
        const csvContent = generateCSV(telemetry, filters, workspaceName, userName, timestamp);
        const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
        triggerDownload(blob, filename);
      } else if (format === "excel") {
        const excelContent = generateExcelXML(telemetry, filters, workspaceName, userName, timestamp);
        const blob = new Blob([excelContent], {
          type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        });
        triggerDownload(blob, filename);
      } else {
        // PDF Report Generation
        await generatePDFReport(telemetry, filters, workspaceName, userName, timestamp, filename);
      }
    } catch (error) {
      console.error("[Analytics Export Error]: Failed to generate report.", error);
      throw error;
    }
  },
};

// ── Helper: Trigger Browser Blob Download ──────────────────────────────────

function triggerDownload(blob: Blob, filename: string): void {
  const url = window.URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.setAttribute("download", filename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  window.URL.revokeObjectURL(url);
}

// ── CSV Generator ──────────────────────────────────────────────────────────

function generateCSV(
  t: SystemTelemetryData,
  filters: ExportFilters,
  wsName: string,
  userName: string,
  timestamp: string
): string {
  const lines: string[] = [
    `"NeuroDesk AI - Analytics & System Telemetry Report"`,
    `"Workspace Name","${wsName}"`,
    `"Generated At","${timestamp}"`,
    `"Generated By","${userName}"`,
    `"Date Range Scope","${filters.dateRange}"`,
    `"Category Scope","${filters.selectedCategory}"`,
    `"Owner Scope","${filters.selectedOwner}"`,
    "",
    `"EXECUTIVE SUMMARY METRICS"`,
    `"Metric Name","Value"`,
    `"Total Workspaces",${t.workspaces.total}`,
    `"Active Workspaces",${t.workspaces.active}`,
    `"Archived Workspaces",${t.workspaces.archived}`,
    `"Workspace Growth Percentage","${t.workspaces.growth_percentage}%"`,
    `"Total Files Uploaded",${t.files.total}`,
    `"Files Uploaded Today",${t.files.today}`,
    `"Files Uploaded This Week",${t.files.this_week}`,
    `"Files Uploaded This Month",${t.files.this_month}`,
    `"Total Documents",${t.documents.total}`,
    `"Indexed Documents",${t.documents.indexed}`,
    `"Pending Documents",${t.documents.pending}`,
    `"Failed Documents",${t.documents.failed}`,
    `"Total Datasets",${t.datasets.total}`,
    `"Total Dataset Files",${t.datasets.files_count}`,
    `"Indexed Datasets",${t.datasets.indexed}`,
    `"Total Storage Used","${t.storage.used_formatted}"`,
    `"Remaining Storage","${t.storage.remaining_formatted}"`,
    `"Total Storage Capacity","${t.storage.capacity_formatted}"`,
    `"Storage Usage Percentage","${t.storage.percentage_used}%"`,
    `"Average File Size","${t.storage.avg_file_size_formatted}"`,
    `"Total Team Members",${t.team.total_members}`,
    `"Active Team Members",${t.team.active_members}`,
    `"Reports Submitted",${t.team.reports_submitted}`,
    `"Files Per User",${t.team.files_per_user}`,
    `"Most Active User","${t.team.most_active_user}"`,
    `"Total Background Jobs",${t.jobs.total}`,
    `"Running Jobs",${t.jobs.running}`,
    `"Completed Jobs",${t.jobs.completed}`,
    `"Failed Jobs",${t.jobs.failed}`,
    "",
    `"STORAGE ASSET DISTRIBUTION BY FILE TYPE"`,
    `"File Type","File Count","Total Size","Percentage"`,
  ];

  t.charts.storage_distribution.forEach((item) => {
    lines.push(`"${item.name}",${item.count},"${item.formatted_size}","${item.percentage}%"`);
  });

  lines.push("", `"CATEGORY BREAKDOWN"`, `"Category","Item Count","Total Size"`);
  t.charts.category_distribution.forEach((item) => {
    lines.push(`"${item.category}",${item.count},"${item.formatted_size}"`);
  });

  lines.push("", `"LARGEST STORED ASSETS"`, `"File Name","File Type","Size","Uploaded Date"`);
  t.files.largest_files.forEach((f) => {
    lines.push(`"${f.name}","${f.file_type}","${f.size_formatted}","${f.created_at || "N/A"}"`);
  });

  return lines.join("\n");
}

